#!/bin/sh
# Smoke test for the legacy C/Bash deliverables (logger.so, acmonitor,
# ransomware.sh). Everything happens inside a disposable temporary
# directory; nothing in the project directory is read, modified or deleted.
set -eu

here="$(cd "$(dirname "$0")/.." && pwd)"
# /tmp is typically mounted noexec in CI/containers (including this repo's
# Docker sandbox); build the scratch directory next to the sources instead,
# where test_aclog/acmonitor/ransomware.sh can actually be executed.
work="$(mktemp -d "$here/.check-legacy.XXXXXX")"
trap 'rm -rf "$work"' EXIT

cp "$here/logger.so" "$here/acmonitor" "$here/test_aclog" "$here/ransomware.sh" "$work/"
cd "$work"

echo "== test_aclog: generating denied / modified / recent / encrypted events =="
ACLOG_PATH="$work/file_logging.log" LD_PRELOAD="$work/logger.so" "$work/test_aclog"
test -s file_logging.log

echo "== acmonitor -m: expect the test user over the 7-distinct-denied-file threshold =="
ACLOG_PATH="$work/file_logging.log" "$work/acmonitor" -m | tee /tmp/am-m.$$ >&2
grep -q "$(id -u)" /tmp/am-m.$$
rm -f /tmp/am-m.$$

echo "== acmonitor -i: expect two recorded modifications of aclog-test/modified.txt =="
ACLOG_PATH="$work/file_logging.log" "$work/acmonitor" -i "$work/aclog-test/modified.txt" | tee /tmp/am-i.$$ >&2
grep -qE "^$(id -u)[[:space:]]+2$" /tmp/am-i.$$
rm -f /tmp/am-i.$$

echo "== acmonitor -v: low threshold reached, high threshold not =="
ACLOG_PATH="$work/file_logging.log" "$work/acmonitor" -v 5 | grep -q "Threshold reached: yes"
ACLOG_PATH="$work/file_logging.log" "$work/acmonitor" -v 1000 | grep -q "Threshold reached: no"

echo "== acmonitor -e: expect the open-then-encrypt pair generated by test_aclog =="
ACLOG_PATH="$work/file_logging.log" "$work/acmonitor" -e | grep -q "secret.txt.encrypt"

echo "== ransomware.sh: create, encrypt+delete, decrypt round trip on throwaway fixtures =="
mkdir lab
echo "fixture one" >lab/one.txt
echo "fixture two" >lab/two.txt
"$work/ransomware.sh" -n 3 -d lab
test -f lab/file1.txt && test -f lab/file2.txt && test -f lab/file3.txt
"$work/ransomware.sh" -e -d lab -p 'correct horse battery staple'
[ ! -e lab/one.txt ] && [ ! -e lab/two.txt ]
test -f lab/one.txt.encrypt && test -f lab/two.txt.encrypt
"$work/ransomware.sh" -x -d lab -p 'correct horse battery staple'
[ "$(cat lab/one.txt)" = "fixture one" ]
[ "$(cat lab/two.txt)" = "fixture two" ]

echo "== ransomware.sh: wrong password must not fabricate plaintext =="
mkdir lab2
echo "fixture three" >lab2/three.txt
"$work/ransomware.sh" -e -d lab2 -p 'correct horse battery staple' >/dev/null
if "$work/ransomware.sh" -x -d lab2 -p 'wrong password' >/dev/null 2>&1; then
	echo "decrypt with the wrong password should have failed" >&2
	exit 1
fi
[ ! -e lab2/three.txt ]

echo "All legacy smoke tests passed."
